#!/usr/bin/env python3
"""Generates (1) pblite-free .proto copies for protoc-gen-swift and (2) PBLiteSchema.swift.
Run from repo root: python3 tools/gen_schema.py"""
import os, re, subprocess, sys, tempfile, shutil
from grpc_tools import protoc
from google.protobuf import descriptor_pb2

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Protos")
SWIFT_PROTOS = os.path.join(ROOT, "Protos-Swift")
OUT = os.path.join(ROOT, "Sources/GMessagesMac/Generated/PBLiteSchema.swift")
files = sorted(f for f in os.listdir(SRC) if f.endswith(".proto"))

# 1. descriptor set (needs pblite.proto so the custom option is parsed)
with tempfile.NamedTemporaryFile(suffix=".desc", delete=False) as t:
    desc_path = t.name
inc = os.path.join(os.path.dirname(protoc.__file__), "_proto")
rc = protoc.main(["protoc", f"-I{SRC}", f"-I{inc}", "--include_imports",
                  f"--descriptor_set_out={desc_path}"] + files)
if rc: sys.exit("protoc failed")
fds = descriptor_pb2.FileDescriptorSet(); fds.ParseFromString(open(desc_path, "rb").read())

enums, msgs = set(), {}
def walk(prefix, m, pkg):
    full = f"{prefix}.{m.name}"
    msgs[full] = m
    for e in m.enum_type: enums.add(f"{full}.{e.name}")
    for n in m.nested_type: walk(full, n, pkg)
for f in fds.file:
    if f.package in ("pblite", "google.protobuf"): continue
    for e in f.enum_type: enums.add(f"{f.package}.{e.name}")
    for m in f.message_type: walk(f.package, m, f.package)

K = descriptor_pb2.FieldDescriptorProto
KIND = {K.TYPE_INT32:"int",K.TYPE_INT64:"int",K.TYPE_UINT32:"uint",K.TYPE_UINT64:"uint",
        K.TYPE_BOOL:"bool",K.TYPE_STRING:"string",K.TYPE_BYTES:"bytes",K.TYPE_FLOAT:"float",
        K.TYPE_DOUBLE:"double",K.TYPE_FIXED64:"fixed64",K.TYPE_FIXED32:"fixed32",
        K.TYPE_SFIXED32:"fixed32",K.TYPE_SFIXED64:"fixed64",K.TYPE_SINT32:"sint",K.TYPE_SINT64:"sint",
        K.TYPE_ENUM:"enumeration",K.TYPE_MESSAGE:"message"}

def is_binary(field):
    # extension 50000 = pblite_binary; stored as unknown field in options
    raw = field.options.SerializeToString()
    return b"\x80\xb5\x18\x01" in raw  # tag(50000, varint) = 80 b5 18, value 1

lines = ["// GENERATED by tools/gen_schema.py - do not edit.", "",
         "enum PBKind { case int, uint, sint, bool, string, bytes, float, double, fixed32, fixed64, enumeration, message }",
         "struct PBField { let number: Int; let kind: PBKind; let repeated: Bool; let message: String?; let binary: Bool }", "",
         "enum PBLiteSchema {", "    static let messages: [String: [Int: PBField]] = ["]
for full in sorted(msgs):
    m = msgs[full]
    rows = []
    for fl in m.field:
        k = KIND[fl.type]
        ref = fl.type_name.lstrip(".") if fl.type == K.TYPE_MESSAGE else None
        ref_s = ('"' + ref + '"') if ref else "nil"
        rep_s = "true" if fl.label == K.LABEL_REPEATED else "false"
        bin_s = "true" if is_binary(fl) else "false"
        rows.append("%d: PBField(number: %d, kind: .%s, repeated: %s, message: %s, binary: %s)"
                    % (fl.number, fl.number, k, rep_s, ref_s, bin_s))
    body = ", ".join(rows) if rows else ":"
    lines.append('        "%s": [%s],' % (full, body))
lines += ["    ]", "}"]
open(OUT, "w").write("\n".join(lines) + "\n")

# 2. pblite-free protos for Swift codegen
shutil.rmtree(SWIFT_PROTOS, ignore_errors=True); os.makedirs(SWIFT_PROTOS)
for f in files:
    s = open(os.path.join(SRC, f)).read()
    s = re.sub(r'import "vendor/pblite.proto";\n', "", s)
    s = re.sub(r"\s*\[\(pblite\.pblite_binary\) = true\]", "", s)
    open(os.path.join(SWIFT_PROTOS, f), "w").write(s)
print(f"{len(msgs)} messages -> {OUT}")
